#!/usr/bin/env python3
"""Turn the OurAirports airport-codes CSV into a SQL seed migration.

The CSV stores one coordinates field as "latitude, longitude". This writes
coordinates_lat and coordinates_long as numeric literals for double precision
columns, matching live flight positions.

Run once when the source dataset changes, then commit the generated SQL.
Production applies that file with psql; it does not run this script.

    python3 services/politburo/migrations/scripts/generate_airports_seed.py \
        --csv /path/to/airport-codes.csv
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import sys
from pathlib import Path

SOURCE_URL = (
    "https://raw.githubusercontent.com/datasets/airport-codes/refs/heads/main/data/airport-codes.csv"
)

COLUMNS = (
    "ident",
    "type",
    "name",
    "elevation_ft",
    "continent",
    "iso_country",
    "iso_region",
    "municipality",
    "icao_code",
    "iata_code",
    "coordinates_lat",
    "coordinates_long",
)

REQUIRED = (
    "ident",
    "type",
    "name",
    "continent",
    "iso_country",
    "iso_region",
)

NULLABLE = ("elevation_ft", "municipality", "icao_code", "iata_code")

ALLOWED_TYPES = {
    "heliport",
    "small_airport",
    "closed",
    "medium_airport",
    "seaplane_base",
    "large_airport",
    "balloonport",
}


def copy_text(value: str) -> str:
    return (
        value.replace("\\", "\\\\")
        .replace("\b", "\\b")
        .replace("\f", "\\f")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
        .replace("\v", "\\v")
    )


def split_coordinates(raw: str, ident: str) -> tuple[str, str]:
    parts = [part.strip() for part in raw.split(",")]
    if len(parts) != 2 or not parts[0] or not parts[1]:
        raise SystemExit(f"{ident}: expected \"latitude, longitude\", got {raw!r}")
    lat_s, lon_s = parts
    try:
        lat = float(lat_s)
        lon = float(lon_s)
    except ValueError as exc:
        raise SystemExit(f"{ident}: coordinates are not numbers: {raw!r}") from exc
    if not (-90 <= lat <= 90 and -180 <= lon <= 180):
        raise SystemExit(f"{ident}: coordinates out of range: {raw!r}")
    return lat_s, lon_s


def row_fields(row: dict[str, str]) -> list[str]:
    ident = row["ident"].strip()
    if not ident:
        raise SystemExit("row with empty ident")
    airport_type = row["type"].strip()
    if airport_type not in ALLOWED_TYPES:
        raise SystemExit(f"{ident}: unknown type {airport_type!r}")

    fields: list[str] = []
    for column in COLUMNS:
        if column == "coordinates_lat":
            lat_s, _ = split_coordinates(row["coordinates"], ident)
            fields.append(lat_s)
            continue
        if column == "coordinates_long":
            _, lon_s = split_coordinates(row["coordinates"], ident)
            fields.append(lon_s)
            continue
        value = row[column].strip()
        if column in REQUIRED and not value:
            raise SystemExit(f"{ident}: empty {column}")
        if column == "elevation_ft" and value:
            try:
                int(value)
            except ValueError as exc:
                raise SystemExit(f"{ident}: elevation_ft is not an integer: {value!r}") from exc
        if column in NULLABLE and not value:
            fields.append(r"\N")
        else:
            fields.append(copy_text(value))
    return fields


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def generate(csv_path: Path, out_path: Path) -> int:
    digest = sha256(csv_path)
    count = 0
    seen: set[str] = set()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open(newline="", encoding="utf-8") as source, out_path.open(
        "w", encoding="utf-8", newline="\n"
    ) as out:
        reader = csv.DictReader(source)
        missing = {"ident", "type", "name", "elevation_ft", "continent", "iso_country", "iso_region", "municipality", "icao_code", "iata_code", "coordinates"} - set(reader.fieldnames or [])
        if missing:
            raise SystemExit(f"CSV is missing columns: {', '.join(sorted(missing))}")

        out.write(
            "-- Airport reference seed. Apply after 006_airports.sql.\n"
            "-- Generated by services/politburo/migrations/scripts/generate_airports_seed.py\n"
            f"-- Source: {SOURCE_URL}\n"
            f"-- Source SHA-256: {digest}\n"
            "-- gps_code and local_code from the CSV are not loaded.\n"
            "-- The CSV coordinates field is \"latitude, longitude\"; this file stores\n"
            "-- those as coordinates_lat and coordinates_long numeric literals.\n"
            "-- Do not edit by hand. Regenerate this file when the source dataset changes.\n"
            "\n"
            "COPY public.airports (\n"
            "    ident,\n"
            "    type,\n"
            "    name,\n"
            "    elevation_ft,\n"
            "    continent,\n"
            "    iso_country,\n"
            "    iso_region,\n"
            "    municipality,\n"
            "    icao_code,\n"
            "    iata_code,\n"
            "    coordinates_lat,\n"
            "    coordinates_long\n"
            ") FROM stdin;\n"
        )
        for row in reader:
            ident = row["ident"].strip()
            if ident in seen:
                raise SystemExit(f"duplicate ident {ident}")
            seen.add(ident)
            out.write("\t".join(row_fields(row)))
            out.write("\n")
            count += 1
        out.write("\\.\n")
    if count == 0:
        raise SystemExit("CSV contained no airport rows")
    return count


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=Path, help="airport-codes.csv path")
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "007_airports_seed.sql",
        help="SQL seed path (default: migrations/007_airports_seed.sql)",
    )
    args = parser.parse_args()
    count = generate(args.csv, args.out)
    print(f"wrote {count} airports to {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
